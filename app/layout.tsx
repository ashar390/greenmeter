import type { Metadata } from "next";
import { Geist, Geist_Mono } from "next/font/google";
import { headers } from "next/headers";
import "./globals.css";

const geistSans = Geist({
  variable: "--font-geist-sans",
  subsets: ["latin"],
});

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

export async function generateMetadata(): Promise<Metadata> {
  const requestHeaders = await headers();
  const host = requestHeaders.get("host") ?? "localhost:3000";
  const protocol = requestHeaders.get("x-forwarded-proto") ?? (host.startsWith("localhost") ? "http" : "https");
  const imageUrl = `${protocol}://${host}/og.png`;

  return {
    title: "GreenMeter | Household Energy Insights",
    description: "Track household utility usage, understand your carbon impact, and build practical energy-saving habits.",
    openGraph: {
      title: "GreenMeter",
      description: "Understand your usage. Lower your impact.",
      images: [{ url: imageUrl, width: 1734, height: 907, alt: "GreenMeter household energy analytics" }],
    },
    twitter: {
      card: "summary_large_image",
      title: "GreenMeter",
      description: "Understand your usage. Lower your impact.",
      images: [imageUrl],
    },
  };
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en">
      <body
        className={`${geistSans.variable} ${geistMono.variable} antialiased`}
      >
        {children}
      </body>
    </html>
  );
}
